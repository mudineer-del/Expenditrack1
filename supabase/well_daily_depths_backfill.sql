insert into public.well_daily_depths (well_id, entry_date, depth_md, depth_tvd, source)
select w.id, s.entry_date, s.depth_md, s.depth_tvd, 'import'
from depth_src s
join public.wells w
  on regexp_replace(regexp_replace(upper(w.name), '[^A-Z0-9]', '', 'g'), '0+([0-9])', '\1', 'g')
   = regexp_replace(regexp_replace(upper(s.well_name), '[^A-Z0-9]', '', 'g'), '0+([0-9])', '\1', 'g')
on conflict (well_id, entry_date) do update
  set depth_md = excluded.depth_md,
      depth_tvd = excluded.depth_tvd,
      source = excluded.source,
      updated_at = now();

